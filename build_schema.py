#!/usr/bin/env python3
"""Turn the design export from Supabase (data/schema.csv: kind,name,body) into SQL
for a plain PostgreSQL: tables -> functions -> views, plus read-only access for the
public role (anon) and full access for the sync script (service_role)."""
import csv
import re
import sys

csv.field_size_limit(10**9)
rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8-sig")))
tables = [r for r in rows if r["kind"] == "TABLE"]
funcs = [r for r in rows if r["kind"] == "FUNCTION"]
views = [r for r in rows if r["kind"] == "VIEW"]

# primary keys the sync script relies on for upserts (not in the export)
PK = {"plots": "id", "nuca_news": "nid", "no_allocation_days": "day"}
PUBLIC_READ = {"plots", "plot_changes", "scrape_runs", "nuca_news", "no_allocation_days"}

out = ["-- generated by build_schema.py", "set check_function_bodies = off;"]


def split_cols(body):
    # columns are joined with ", " but defaults can contain commas inside (...) / '...'
    parts, depth, cur, q = [], 0, "", False
    i = 0
    while i < len(body):
        ch = body[i]
        if ch == "'":
            q = not q
        if not q:
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif ch == "," and depth == 0 and body[i:i + 2] == ", ":
                parts.append(cur.strip()); cur = ""; i += 2; continue
        cur += ch; i += 1
    if cur.strip():
        parts.append(cur.strip())
    return parts


for t in tables:
    name = t["name"]
    cols = []
    for c in split_cols(t["body"]):
        m = re.match(r"(\w+) (.+?)( default .+?)?( not null)?$", c)
        if not m:
            cols.append(c); continue
        col, typ, dflt, nn = m.group(1), m.group(2), (m.group(3) or ""), (m.group(4) or "")
        if typ == "ARRAY":
            typ = "text[]"
        if typ == "USER-DEFINED":
            typ = "text"
        if "nextval(" in dflt:                               # serial column
            typ = "bigserial" if "bigint" in typ else "serial"; dflt = ""
        dflt = dflt.replace("uuid_generate_v4()", "gen_random_uuid()").replace("extensions.", "")
        if re.search(r"\b(auth|storage)\.", dflt):          # Supabase-only helpers
            dflt = ""
        if col == "id" and not dflt and typ in ("bigint", "integer") and name not in PK:
            typ += " generated by default as identity"
        pk = " primary key" if PK.get(name, "id") == col else ""
        cols.append(f"{col} {typ}{dflt}{nn if not pk else ''}{pk}")
    out.append(f"create table if not exists public.{name} (\n  " + ",\n  ".join(cols) + "\n);")

for f in funcs:
    out.append(f["body"].rstrip().rstrip(";") + ";")

out.append("-- views (created by setup.sh in a retry loop: they can depend on each other)")
open("schema_tables.sql", "w", encoding="utf-8").write("\n\n".join(out) + "\n")
with open("schema_views.tsv", "w", encoding="utf-8") as fh:
    for v in views:
        fh.write(v["name"] + "\t" + v["body"].replace("\t", " ").replace("\n", " ").strip().rstrip(";") + "\n")

grants = ["grant usage on schema public to anon, service_role;",
          "grant all on all tables in schema public to service_role;",
          "grant all on all sequences in schema public to service_role;",
          "alter default privileges in schema public grant all on tables to service_role;",
          "alter default privileges in schema public grant all on sequences to service_role;"]
for t in tables:
    n = t["name"]
    grants.append(f"alter table public.{n} enable row level security;")
    if n in PUBLIC_READ:
        grants.append(f"grant select on public.{n} to anon;")
        grants.append(f"drop policy if exists read_all on public.{n};")
        grants.append(f"drop policy if exists read_recent on public.{n};")
        if n == "plot_changes":   # booking history: the public sees only the last days (the full history stays private)
            grants.append(f"create policy read_recent on public.{n} for select to anon using (created_at >= now() - interval '8 days');")
        else:
            grants.append(f"create policy read_all on public.{n} for select to anon using (true);")
for v in views:
    grants.append(f"grant select on public.{v['name']} to anon;")
for f in funcs:
    m = re.search(r"FUNCTION (public\.\w+\([^)]*\))", f["body"])
    if m:
        grants.append(f"grant execute on function {m.group(1)} to anon, service_role;")
open("schema_grants.sql", "w", encoding="utf-8").write("\n".join(grants) + "\n")
print(f"tables {len(tables)}, functions {len(funcs)}, views {len(views)}")
